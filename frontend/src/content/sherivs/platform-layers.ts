/**
 * Sherivs public content — the platform layers.
 *
 * One record per layer of the platform. Each record states only what the platform
 * actually does today and names the internal module family that backs every claim
 * (`evidence`), so a claim on the public site can be traced to code. `evidence` is for
 * governance and tests — it is never rendered.
 *
 * Availability vocabulary (honest, two values):
 *   - "in_service": customers use this layer through product surfaces today.
 *   - "foundation": the governed substrate is built and tested; product surfaces are
 *     being composed on it. The page says so.
 */
export type LayerAvailability = "in_service" | "foundation";

export interface LayerCapability {
  title: string;
  detail: string;
}

export interface PlatformLayer {
  slug: string;
  /** Two-digit position in the platform narrative. */
  index: string;
  name: string;
  /** One-line statement of the layer's job. */
  statement: string;
  /** The organizational problem the layer answers. */
  problem: string;
  capabilities: readonly LayerCapability[];
  /** Rules the layer will not break, phrased for customers. */
  guarantees: readonly string[];
  availability: LayerAvailability;
  /** Repository module families that implement the claims (never rendered). */
  evidence: readonly string[];
}

