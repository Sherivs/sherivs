/**
 * CoreGrid — verification independence enforcement (J-035 / MISSION H2-17).
 *
 * J-035 (STREAM_J_GAP_DISCOVERY): "a worker (AI or human) cannot verify its
 * own output in the loop". E-050 — an AI worker must not validate its own
 * unsupported claim — and AGENTS.md §21 (AI output trust: AI output is
 * untrusted by default) make the Verification node self-confirming unless a
 * binding rule exists. This module owns that rule for the mission/worker
 * substrate: a verification verdict on a work item can ONLY be issued by an
 * identity that
 *   (a) is not the performer of record for that item,
 *   (b) holds the declared verifier capability AT EVALUATION TIME,
 *   (c) records provenance — who verified what, under which policy, when
 *       (Constitution §12), and whether the verifier is AI (§12 "was it
 *       generated by AI?").
 *
 * Fail closed (Constitution §16/§31): a missing or ambiguous performer of
 * record, a self-verification attempt, a capability not held at evaluation
 * time, a cross-tenant verifier, and any malformed input are all DENIED with
 * a named reason. Every evaluation — allow AND deny — produces an immutable
 * audit record (§18: Observe -> Evaluate -> Decision -> Audit), so denial is
 * observable, never silent.
 *
 * Capability checks evaluate FRESH from the inputs on every call: nothing is
 * cached past revocation. A verifier whose held capability set no longer
 * contains the item's required verifier capability is denied on the next
 * evaluation (revocation propagation, mirroring the capability registry).
 *
 * Composition: the work item's performer of record comes from the
 * mission/delegation execution records (`mission/delegation-contract.ts`
 * `DelegatedActionRecord`), the verifier's capability vocabulary from the
 * workforce substrate (`workforce/capability-registry.ts`), and the policy
 * reference from the work item's governing policy. This module owns none of
 * those sources — it resolves and evaluates against what they record.
 *
 * Boundary: pure data + pure functions. No persistence, no I/O, no vendor
 * imports, no implicit clock — the caller supplies the verification instant.
 */

/* ─────────────────────────────────────────────────────────────
 * Vocabularies
 * ────────────────────────────────────────────────────────────*/

/** The verdict kinds an independent verifier may issue on a work item. */
export type VerdictKind = "verified" | "rejected";

export const VERDICT_KINDS: readonly VerdictKind[] = ["verified", "rejected"] as const;

/**
 * Verifier classification (Constitution §12 provenance: "was it generated by
 * AI?"). Mirrors the workforce substrate's worker classification vocabulary
 * (`worker-definition.ts` WorkerClassification) plus the explicit
 * "unclassified" default — an unclassified verifier is still evaluable;
 * classification is PROVENANCE here, not an authority axis (the independence
 * law binds identity, not kind: AI and human verifiers are equally barred
 * from verifying their own output).
 */
export type VerifierClassification = "human" | "ai" | "unclassified";

export const VERIFIER_CLASSIFICATIONS: readonly VerifierClassification[] = [
  "human",
  "ai",
  "unclassified",
] as const;

/**
 * The closed set of fail-closed denial reasons. Every non-allow path names
 * its reason (never a silent pass).
 */
export type VerificationDenyReason =
  | "invalid_attempt"
  | "invalid_item"
  | "cross_tenant_verifier_denied"
  | "performer_of_record_unrecorded"
  | "performer_of_record_ambiguous"
  | "self_verification_denied"
  | "required_verifier_capability_not_held";

/* ─────────────────────────────────────────────────────────────
 * Work item — the verified object and its performer of record
 * ────────────────────────────────────────────────────────────*/

/**
 * Performer of record for a work item: the identity the execution records
 * name as the performer. The three states are EXPLICIT — "unrecorded" and
 * "ambiguous" are first-class, because a verdict issued against an item
 * whose performer cannot be resolved is unverifiable for independence and
 * must be denied (fail closed), not guessed.
 */
export type PerformerOfRecord =
  | { readonly status: "recorded"; readonly identityRef: string }
  | { readonly status: "unrecorded" }
  | { readonly status: "ambiguous"; readonly candidates: readonly string[] };

/** A work item a verdict may be issued on. */
export interface VerifiableWorkItem {
  readonly itemId: string;
  /** Tenant scope of the item (multi-tenancy law §13: never null). */
  readonly tenantScope: string;
  readonly performerOfRecord: PerformerOfRecord;
  /**
   * The capability id a verifier MUST hold to issue a verdict on this item
   * (declared verifier capability). A verdict without the capability is
   * denied — the capability, not the requester, is the authority.
   */
  readonly requiredVerifierCapability: string;
  /** The governing policy for verification of this item (§43: under which policy). */
  readonly policyRef: string;
}

/* ─────────────────────────────────────────────────────────────
 * Verifier and attempt
 * ────────────────────────────────────────────────────────────*/

/** The verifying identity and the capabilities it holds AT EVALUATION TIME. */
export interface VerifierIdentity {
  readonly identityRef: string;
  /** Tenant scope of the verifier; must equal the item's tenant scope. */
  readonly tenantScope: string;
  /**
   * Capability ids held at evaluation time (fresh set — revocation is
   * propagated by recomputation, never by cache). Duplicate and blank
   * entries are normalized away before the membership check.
   */
  readonly heldCapabilities: readonly string[];
  /** Provenance-only classification (§12); defaults to "unclassified". */
  readonly classification?: VerifierClassification;
}

/** A verdict issuance attempt by a verifier on a work item. */
export interface VerificationAttempt {
  /** Unique attempt id; anchors the audit record. */
  readonly attemptId: string;
  readonly verifier: VerifierIdentity;
  /** The verdict the verifier attempts to issue. */
  readonly verdict: VerdictKind;
  /** The verifier's stated rationale (a verdict without a reason is not a verdict). */
  readonly reason: string;
  /** Verification instant — supplied by the caller; no implicit clock. */
  readonly verifiedAt: string;
}

/* ─────────────────────────────────────────────────────────────
 * Provenance and audit (Constitution §12 / §18)
 * ────────────────────────────────────────────────────────────*/

/**
 * Provenance of an ISSUED verdict: who verified what, under which policy,
 * when — plus the declared verifier capability the issuance rested on and
 * the verifier's AI-or-human classification.
 */
export interface VerificationProvenance {
  readonly verifiedBy: string;
  readonly verifiedByClassification: VerifierClassification;
  readonly verifiedAt: string;
  readonly subjectItemId: string;
  readonly subjectPerformerRef: string;
  readonly verdict: VerdictKind;
  readonly reason: string;
  readonly requiredVerifierCapability: string;
  readonly policyRef: string;
  readonly tenantScope: string;
}

/**
 * Immutable audit record produced by EVERY evaluation, allow and deny
 * (§18 — denial is observable, never silent). `performerOfRecordRef` is
 * null when the performer of record is unrecorded or ambiguous;
 * `decidedAt` is null when the attempt's verification instant is not a
 * parseable timestamp.
 */
export interface VerificationAuditRecord {
  readonly auditId: string;
  readonly eventKind: "verdict_issued" | "verdict_denied";
  readonly attemptId: string;
  readonly tenantScope: string;
  readonly itemId: string;
  readonly performerOfRecordRef: string | null;
  readonly verifierIdentityRef: string;
  readonly verifierClassification: VerifierClassification;
  readonly attemptedVerdict: VerdictKind;
  readonly requiredVerifierCapability: string;
  readonly policyRef: string;
  readonly decidedAt: string | null;
  readonly denyReason: VerificationDenyReason | null;
  readonly selfVerificationAttempt: boolean;
}

/* ─────────────────────────────────────────────────────────────
 * Evaluation result
 * ────────────────────────────────────────────────────────────*/

export type VerificationEvaluation =
  | { ok: true; verdict: VerificationProvenance; audit: VerificationAuditRecord }
  | {
      ok: false;
      denyReason: VerificationDenyReason;
      detail: string;
      audit: VerificationAuditRecord;
    };

/* ─────────────────────────────────────────────────────────────
 * Helpers (pure, fail closed)
 * ────────────────────────────────────────────────────────────*/

function isNonEmptyTrimmed(value: unknown, maxLength: number): value is string {
  return typeof value === "string" && value.trim().length >= 1 && value.trim().length <= maxLength;
}

function isContractTimestamp(value: unknown): value is string {
  return (
    typeof value === "string" &&
    value.trim().length > 0 &&
    Number.isFinite(Date.parse(value.trim()))
  );
}

function isStringArray(value: unknown): value is readonly string[] {
  return Array.isArray(value) && value.every((entry) => typeof entry === "string");
}

/** Normalize a capability list: trim, drop blanks, deduplicate, keep order. */
function normalizeCapabilities(values: readonly string[]): readonly string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const value of values) {
    const trimmed = value.trim();
    if (trimmed.length === 0 || seen.has(trimmed)) continue;
    seen.add(trimmed);
    out.push(trimmed);
  }
  return out;
}

/**
 * Resolve the performer of record. Fail-closed normalizations: a "recorded"
 * status with a blank identity ref is NOT a performer of record (it
 * downgrades to unrecorded — never guessed), and an "ambiguous" status with
 * fewer than two distinct non-blank candidates is not genuinely ambiguous
 * (0 usable candidates downgrades to unrecorded; exactly 1 resolves to
 * recorded).
 */
export function resolvePerformerOfRecord(performer: PerformerOfRecord): PerformerOfRecord {
  if (performer.status === "recorded") {
    const identityRef = performer.identityRef.trim();
    return identityRef.length === 0
      ? { status: "unrecorded" }
      : { status: "recorded", identityRef };
  }
  if (performer.status === "ambiguous") {
    const candidates = [
      ...new Set(
        performer.candidates.map((candidate) => candidate.trim()).filter((c) => c.length > 0),
      ),
    ];
    if (candidates.length === 0) return { status: "unrecorded" };
    if (candidates.length === 1) return { status: "recorded", identityRef: candidates[0]! };
    return { status: "ambiguous", candidates };
  }
  return { status: "unrecorded" };
}

/** Normalize a verifier classification: anything outside the vocabulary is "unclassified". */
function normalizeVerifierClassification(value: unknown): VerifierClassification {
  return (VERIFIER_CLASSIFICATIONS as readonly string[]).includes(value as string)
    ? (value as VerifierClassification)
    : "unclassified";
}

/**
 * THE independence invariant (J-035): the verifier identity must differ from
 * the performer of record. Identity comparison is over trimmed identity
 * refs; equivalence-class resolution (delegated actors resolving to the same
 * principal) is owned by the identity layer and is not re-implemented here.
 */
export function isSelfVerification(verifierRef: string, performerRef: string): boolean {
  return verifierRef.trim() === performerRef.trim();
}

/** True when the verifier holds the required capability at evaluation time. */
export function holdsVerifierCapability(
  verifier: VerifierIdentity,
  requiredCapabilityId: string,
): boolean {
  const held = new Set(normalizeCapabilities(verifier.heldCapabilities));
  const required = requiredCapabilityId.trim();
  return held.has(required);
}

/* ─────────────────────────────────────────────────────────────
 * The contract: evaluate a verification attempt (fail closed)
 * ────────────────────────────────────────────────────────────*/

/**
 * Evaluate a verdict attempt against a work item. Denial order (each named):
 *  1. invalid_attempt — malformed attempt (blank ids, unknown verdict kind,
 *     blank reason, unparseable instant, malformed capability list);
 *  2. invalid_item — malformed work item (blank ids, blank policy or
 *     capability declaration);
 *  3. cross_tenant_verifier_denied — verifier tenant != item tenant (§13);
 *  4. performer_of_record_unrecorded — the item's performer cannot be
 *     resolved, so independence cannot even be evaluated;
 *  5. performer_of_record_ambiguous — the execution records disagree on the
 *     performer, so independence cannot be evaluated;
 *  6. self_verification_denied — the verifier IS the performer of record
 *     (J-035/E-050: no worker verifies its own work);
 *  7. required_verifier_capability_not_held — the verifier does not hold the
 *     item's declared verifier capability at evaluation time (revocation
 *     propagates: the fresh held set decides).
 *
 * Every path — allow AND deny — returns an audit record. The issued verdict
 * carries full provenance (who verified what, under which policy, when).
 */
export function evaluateVerification(
  item: VerifiableWorkItem,
  attempt: VerificationAttempt,
): VerificationEvaluation {
  /* 1. Attempt shape (fail closed). */
  const attemptWellFormed =
    isNonEmptyTrimmed(attempt?.attemptId, 200) &&
    isNonEmptyTrimmed(attempt?.verifier?.identityRef, 160) &&
    isNonEmptyTrimmed(attempt?.verifier?.tenantScope, 128) &&
    isStringArray(attempt?.verifier?.heldCapabilities) &&
    (VERDICT_KINDS as readonly string[]).includes(attempt?.verdict) &&
    isNonEmptyTrimmed(attempt?.reason, 2000) &&
    isContractTimestamp(attempt?.verifiedAt);
  if (!attemptWellFormed) {
    return deny(
      item,
      attempt,
      "invalid_attempt",
      "verification attempt is malformed (ids, verdict kind, reason, held capabilities or instant)",
    );
  }
  const verifierClassification = normalizeVerifierClassification(attempt.verifier.classification);

  /* 2. Item shape (fail closed). */
  const itemWellFormed =
    isNonEmptyTrimmed(item?.itemId, 200) &&
    isNonEmptyTrimmed(item?.tenantScope, 128) &&
    isNonEmptyTrimmed(item?.requiredVerifierCapability, 160) &&
    isNonEmptyTrimmed(item?.policyRef, 200) &&
    item?.performerOfRecord !== undefined &&
    item?.performerOfRecord !== null &&
    typeof item.performerOfRecord === "object" &&
    typeof (item.performerOfRecord as PerformerOfRecord).status === "string";
  if (!itemWellFormed) {
    return deny(
      item,
      attempt,
      "invalid_item",
      "verifiable work item is malformed (ids, tenant, policy or required verifier capability)",
    );
  }

  const verifierRef = attempt.verifier.identityRef.trim();
  const decidedAt = attempt.verifiedAt.trim();

  /* 3. Tenant (multi-tenancy law §13). */
  if (attempt.verifier.tenantScope.trim() !== item.tenantScope.trim()) {
    return deny(
      item,
      attempt,
      "cross_tenant_verifier_denied",
      `verifier tenant "${attempt.verifier.tenantScope.trim()}" does not match item tenant "${item.tenantScope.trim()}"`,
      verifierClassification,
    );
  }

  /* 4/5. Performer of record must resolve before independence is evaluable. */
  const performer = resolvePerformerOfRecord(item.performerOfRecord);
  if (performer.status === "unrecorded") {
    return deny(
      item,
      attempt,
      "performer_of_record_unrecorded",
      `work item "${item.itemId.trim()}" has no performer of record — independence cannot be evaluated`,
      verifierClassification,
    );
  }
  if (performer.status === "ambiguous") {
    return deny(
      item,
      attempt,
      "performer_of_record_ambiguous",
      `work item "${item.itemId.trim()}" has an ambiguous performer of record (${performer.candidates.length} candidates) — independence cannot be evaluated`,
      verifierClassification,
    );
  }
  const performerRef = performer.identityRef;

  /* 6. THE independence invariant (J-035 / E-050). */
  if (isSelfVerification(verifierRef, performerRef)) {
    return deny(
      item,
      attempt,
      "self_verification_denied",
      `verifier "${verifierRef}" is the performer of record for "${item.itemId.trim()}" — no worker verifies its own work`,
      verifierClassification,
    );
  }

  /* 7. Declared verifier capability, evaluated fresh (revocation propagation). */
  if (!holdsVerifierCapability(attempt.verifier, item.requiredVerifierCapability)) {
    return deny(
      item,
      attempt,
      "required_verifier_capability_not_held",
      `verifier "${verifierRef}" does not hold required verifier capability "${item.requiredVerifierCapability.trim()}" at evaluation time`,
      verifierClassification,
    );
  }

  /* Allow: issue the verdict with full provenance (§12). */
  const audit = auditRecord(item, attempt, {
    eventKind: "verdict_issued",
    denyReason: null,
    performerRef,
    selfVerificationAttempt: false,
    verifierClassification,
    decidedAt,
  });
  return {
    ok: true,
    verdict: {
      verifiedBy: verifierRef,
      verifiedByClassification: verifierClassification,
      verifiedAt: decidedAt,
      subjectItemId: item.itemId.trim(),
      subjectPerformerRef: performerRef,
      verdict: attempt.verdict,
      reason: attempt.reason.trim(),
      requiredVerifierCapability: item.requiredVerifierCapability.trim(),
      policyRef: item.policyRef.trim(),
      tenantScope: item.tenantScope.trim(),
    },
    audit,
  };
}

/**
 * Build the audit record for a DENIED evaluation. Works even when the item
 * or attempt is malformed: every field is read defensively, so a denial of a
 * malformed input is still observable (fail closed, never silent).
 */
function deny(
  item: VerifiableWorkItem | undefined | null,
  attempt: VerificationAttempt | undefined | null,
  denyReason: VerificationDenyReason,
  detail: string,
  verifierClassification: VerifierClassification = "unclassified",
): {
  ok: false;
  denyReason: VerificationDenyReason;
  detail: string;
  audit: VerificationAuditRecord;
} {
  const performerCandidate: PerformerOfRecord | null =
    item && typeof item === "object" && item.performerOfRecord
      ? resolvePerformerOfRecord(item.performerOfRecord)
      : null;
  const performerRef =
    performerCandidate?.status === "recorded" ? performerCandidate.identityRef : null;
  const verifierRef = isNonEmptyTrimmed(attempt?.verifier?.identityRef, 160)
    ? attempt.verifier.identityRef.trim()
    : "";
  const selfVerificationAttempt =
    verifierRef.length > 0 &&
    performerRef !== null &&
    isSelfVerification(verifierRef, performerRef);
  const audit = auditRecord(item, attempt, {
    eventKind: "verdict_denied",
    denyReason,
    performerRef,
    selfVerificationAttempt,
    verifierClassification,
    decidedAt: isContractTimestamp(attempt?.verifiedAt) ? attempt.verifiedAt.trim() : null,
  });
  return { ok: false, denyReason, detail, audit };
}

function auditRecord(
  item: VerifiableWorkItem | undefined | null,
  attempt: VerificationAttempt | undefined | null,
  fields: {
    eventKind: "verdict_issued" | "verdict_denied";
    denyReason: VerificationDenyReason | null;
    performerRef: string | null;
    selfVerificationAttempt: boolean;
    verifierClassification: VerifierClassification;
    decidedAt: string | null;
  },
): VerificationAuditRecord {
  const attemptId = isNonEmptyTrimmed(attempt?.attemptId, 200)
    ? attempt.attemptId.trim()
    : "unattributed";
  const itemId = isNonEmptyTrimmed(item?.itemId, 200) ? item.itemId.trim() : "unattributed";
  const tenantScope = isNonEmptyTrimmed(item?.tenantScope, 128)
    ? item.tenantScope.trim()
    : isNonEmptyTrimmed(attempt?.verifier?.tenantScope, 128)
      ? attempt.verifier.tenantScope.trim()
      : "unattributed";
  const verifierIdentityRef = isNonEmptyTrimmed(attempt?.verifier?.identityRef, 160)
    ? attempt.verifier.identityRef.trim()
    : "unattributed";
  const attemptedVerdict =
    attempt !== null &&
    attempt !== undefined &&
    (VERDICT_KINDS as readonly string[]).includes(attempt.verdict)
      ? attempt.verdict
      : "verified";
  const requiredVerifierCapability = isNonEmptyTrimmed(item?.requiredVerifierCapability, 160)
    ? item.requiredVerifierCapability.trim()
    : "unattributed";
  const policyRef = isNonEmptyTrimmed(item?.policyRef, 200)
    ? item.policyRef.trim()
    : "unattributed";
  return {
    auditId: `audit:${attemptId}`,
    eventKind: fields.eventKind,
    attemptId,
    tenantScope,
    itemId,
    performerOfRecordRef: fields.performerRef,
    verifierIdentityRef,
    verifierClassification: fields.verifierClassification,
    attemptedVerdict,
    requiredVerifierCapability,
    policyRef,
    decidedAt: fields.decidedAt,
    denyReason: fields.denyReason,
    selfVerificationAttempt: fields.selfVerificationAttempt,
  };
}
