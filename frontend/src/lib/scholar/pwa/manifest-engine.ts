/**
 * CoreGrid Scholar — PWA manifest generation (WAVE-R35).
 *
 * The web app manifest is GENERATED from reality too: the app name and theme
 * come from the brand, and the shortcuts come from the sections the
 * organization's reality actually has (a boarding school gets a boarding-life
 * shortcut because it has that section).
 */

import type { BrandIdentity } from "../experience/experience-brand";
import type { GeneratedExperience } from "../experience/experience-engine";

export interface ManifestIcon {
  src: string;
  sizes: string;
  type: "image/png" | "image/svg+xml" | "image/webp";
  purpose?: "any" | "maskable";
}

export interface ManifestShortcut {
  name: string;
  url: string;
}

export interface WebAppManifest {
  name: string;
  short_name: string;
  description: string;
  start_url: string;
  scope: string;
  display: "standalone" | "fullscreen" | "minimal-ui" | "browser";
  background_color: string;
  theme_color: string;
  lang: string;
  icons: readonly ManifestIcon[];
  shortcuts: readonly ManifestShortcut[];
  categories: readonly string[];
  prefer_related_applications: false;
}

export interface WebAppManifestInput {
  brand: BrandIdentity;
  experience: GeneratedExperience;
  startUrl?: string;
  scope?: string;
  icons?: readonly ManifestIcon[];
}

const DEFAULT_ICONS: readonly ManifestIcon[] = [
  { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
  { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
  { src: "/icons/maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
];

const SHORTCUT_SECTIONS = 4;

export function buildWebAppManifest(input: WebAppManifestInput): WebAppManifest {
  const { brand, experience } = input;
  const startUrl = input.startUrl ?? "/";
  return {
    name: brand.name,
    short_name: brand.name.length > 20 ? `${brand.name.slice(0, 19)}…` : brand.name,
    description: `${brand.name} — generated by Sherivs from the organization's reality.`,
    start_url: startUrl,
    scope: input.scope ?? "/",
    display: "standalone",
    background_color: brand.secondaryColor,
    theme_color: brand.primaryColor,
    lang: brand.language,
    icons: input.icons ?? DEFAULT_ICONS,
    shortcuts: experience.publicNavigation.slice(0, SHORTCUT_SECTIONS).map((section) => ({
      name: section.replace(/_/g, " "),
      url: `${startUrl}#${section}`,
    })),
    categories: ["education", "productivity"],
    prefer_related_applications: false,
  };
}

const SHORTCUT_NAME_RE = /^[a-z0-9 ]+$/;

export function validateWebAppManifest(manifest: WebAppManifest): string[] {
  const issues: string[] = [];
  if (manifest.name.trim().length < 2) issues.push("name is required");
  if (manifest.short_name.trim().length === 0) issues.push("short_name is required");
  if (manifest.short_name.length > 20) issues.push("short_name must be at most 20 characters");
  if (!manifest.start_url.startsWith("/")) issues.push("start_url must be an app-relative path");
  if (!manifest.scope.startsWith("/")) issues.push("scope must be an app-relative path");
  if (manifest.icons.length === 0) issues.push("at least one icon is required");
  if (!manifest.icons.some((icon) => icon.sizes.includes("512"))) {
    issues.push("a 512px icon is required for installability");
  }
  if (!/^#[0-9a-fA-F]{6}$/.test(manifest.theme_color)) issues.push("theme_color must be #RRGGBB");
  if (!/^#[0-9a-fA-F]{6}$/.test(manifest.background_color)) {
    issues.push("background_color must be #RRGGBB");
  }
  for (const shortcut of manifest.shortcuts) {
    if (!SHORTCUT_NAME_RE.test(shortcut.name)) {
      issues.push(`shortcut name "${shortcut.name}" must be lowercase words`);
    }
    if (!shortcut.url.includes("#"))
      issues.push(`shortcut "${shortcut.name}" must target a section`);
  }
  return issues;
}
