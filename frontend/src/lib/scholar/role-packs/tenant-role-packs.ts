/**
 * Sherivs Scholar — first-party tenant Role Packs (ENGINE-01, ADR-078).
 *
 * One pack per membership role the engine serves today. Every permission id is
 * drawn from the generated Nigerian role catalog and is a subset of the
 * matching template (a test enforces this), so a pack can never name authority
 * the role does not already have. The agent proposes and drafts; anything that
 * reaches a parent, a student or a record is approval-gated, and no pack
 * declares an action above T2.
 *
 * Roles with no pack here (hq, alumni, driver and the finer catalog templates)
 * still get a twin context: it waits as `pending_pack` and the agent appears
 * the moment a pack is published for that role.
 */
