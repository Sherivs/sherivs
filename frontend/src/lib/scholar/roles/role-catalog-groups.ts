/**
 * Sherivs Scholar — Educational Reality Role Engine: catalog group data.
 *
 * The directive's reality catalog, expressed as GROUPS (not as engine logic).
 * A group declares which reality gives its roles a home using the EXISTING
 * institution vocabulary (feature keys + template ids from
 * `runtime/scholar-school-templates.ts`) plus education levels and
 * jurisdictions. `role-registry.ts` expands groups into role definitions, so a
 * new institution type or curriculum is a DATA change, never an engine change.
 *
 * Staffed groups point at the P25 workforce catalog: the registry links each
 * staffed role to the Scholar workforce kind it IS (title/alias match) instead
 * of redefining the job (no role duplication).
 */

import type { RoleCategory } from "./role-categories";
import type { EducationLevel, RolePriority, RoleStaffingKind } from "./role-definition";

export interface RoleGroup {
  /** Stable group key (audit + documentation). */
  group: string;
  category: RoleCategory;
  /** Existing institution feature keys that give the group a home. */
  featureScope?: readonly string[];
  /** Existing institution template ids the group belongs to. */
  templateRefs?: readonly string[];
  educationLevels?: readonly EducationLevel[];
  jurisdictions?: readonly string[];
  /** Base priority before the template engine promotes it for a real reality. */
  basePriority?: RolePriority;
  /** Staffed groups link to the Scholar workforce catalog; default `non_staff`. */
  staffing?: RoleStaffingKind;
  /** Role names exactly as the reality names them. */
  roles: readonly string[];
}

