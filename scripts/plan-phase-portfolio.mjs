/**
 * CoreGrid — phase portfolio upgrade plan generator.
 *
 * Reads the derived phase-completion status (architecture/phase-completion-status.md) and
 * writes the per-phase plan for the blueprint upgrade: what each phase has, and what it
 * needs to satisfy L4 (a real surface that consumes the phase) — so building 11 → 51 starts
 * from a blueprint that no longer frames one runtime as the platform.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const STATUS = "architecture/phase-completion-status.md";
const OUT = "architecture/phase-portfolio-upgrade-plan.md";

const rows = readFileSync(join(ROOT, STATUS), "utf8")
  .split("\n")
  .filter((line) => /^\|\s*\d{2}\s*\|/.test(line))
  .map((line) => line.split("|").map((cell) => cell.trim()))
  .map((cells) => ({
    id: cells[1],
    name: cells[2],
    capability: cells[3],
    sections: cells[4],
    modules: cells[5],
    tests: cells[6],
    l1: cells[7],
    l2: cells[8],
    l3: cells[9],
    l4: cells[10],
    l5: cells[11],
    derived: cells[12],
    registry: cells[13] ?? "",
  }));

const yes = (value) => /^yes$/i.test(value);
const complete = rows.filter((row) => row.derived.toUpperCase().includes("COMPLETE"));
const missingL4 = rows.filter((row) => !yes(row.l4));
const missingL5 = rows.filter((row) => !yes(row.l5));
const architectureOnly = rows.filter((row) => row.derived.toUpperCase().includes("ARCHITECTURE"));

const plan = [
  "# CoreGrid — phase blueprint upgrade plan (portfolio)",
  "",
  "> Generated by `scripts/plan-phase-portfolio.mjs` from the derived audit",
  "> (`architecture/phase-completion-status.md`), after the blueprint neutrality wave",
  "> (`architecture/phase-blueprint-neutrality-report.md`).",
  ">",
  "> **Framing law, now machine-enforced:** CoreGrid is the platform. An installed runtime",
  "> consumes it; CoreGrid Scholar is runtime-001, the first installed runtime, never the",
  "> platform. `tests/unit/platform-neutrality.test.ts` Laws 1–6 and",
  "> `scripts/normalise-phase-doc-framing.mjs --check` refuse a blueprint that says otherwise.",
  "",
  "## 1. Where the portfolio stands",
  "",
  "| Measure | Value |",
  "| --- | --- |",
  `| Phases audited | ${rows.length} |`,
  `| Derived COMPLETE (all five levels evidenced) | ${complete.length} |`,
  `| Missing L4 (no surface consumes the phase) | ${missingL4.length} |`,
  `| Missing L5 (no operational evidence) | ${missingL5.length} |`,
  `| Architecture-defined phases (not yet built) | ${architectureOnly.length} |`,
  "",
  "## 2. Phases whose derived state is COMPLETE",
  "",
  ...(complete.length === 0
    ? ["None."]
    : complete.map(
        (row) =>
          `- **${row.id} ${row.name}** — ${row.capability}, ${row.modules} modules, ${row.tests} tests`,
      )),
  "",
  "## 3. L4 gap register — what each phase needs next",
  "",
  "L4 is satisfied when a real surface consumes the phase: a route or component that imports",
  "the phase's module (or displays the capability it owns) and **exercises** it rather than",
  "describing it. The standard pattern is the one phases 06–10 used: a `*-report.ts` module",
  "that calls the phase's own contracts and returns observed results plus declared gaps, and a",
  "route that renders it without declaring a role list of its own (Phase 08/RLS enforce access).",
  "",
  "| Phase | Name | Capability | Modules | Tests | L4 | Next L4 artefact |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map(
    (row) =>
      `| ${row.id} | ${row.name} | ${row.capability} | ${row.modules} | ${row.tests} | ${
        yes(row.l4) ? "yes" : "**missing**"
      } | ${
        yes(row.l4)
          ? "—"
          : `a surface that imports \`${row.capability.replace(/[^a-z0-9-]/gi, "")}\`'s module and exercises it`
      } |`,
  ),
  "",
  "## 4. Build order (phase 11 → 51)",
  "",
  "1. Take the lowest-numbered phase that is not COMPLETE.",
  "2. Read its blueprint (now neutral), its contract, its acceptance record and its registry row.",
  "3. Complete the document to 20/20 engineering sections if it is short.",
  "4. Implement what the blueprint describes, with tests, in the phase's own layer.",
  "5. Close L4 with a real surface — exercising, not describing.",
  "6. Close L5 with operational evidence (proof, verifier, runbook or infrastructure naming it).",
  "7. Correct the registry row from evidence, run the acceptance probe, then the full chain",
  "   (`audit:phase --phase=NN`, `audit:phases`, `verify:registry`, `test:unit`, `typecheck`, `build`).",
  "",
  "## 5. Laws that apply to every phase from now on",
  "",
  "1. **Domain neutrality** — no kernel or capability file names a runtime; the platform speaks",
  "   about *an installed runtime*; runtime identity lives in the runtime layer.",
  "2. **Blueprint neutrality** — no phase document presents a runtime as the platform. The",
  "   runtime's own layer may name itself; the blueprint may not.",
  "3. **Ownership** — a phase owns its domain and nothing else; it consumes identity, tenancy,",
  "   authorization and trust rather than re-implementing them.",
  "4. **Canonical truth** — AI inference never overwrites canonical state without validation.",
  "5. **Evidence** — a level is claimed only when an artefact proves it; gaps are declared.",
  "",
];

writeFileSync(join(ROOT, OUT), plan.join("\n"), "utf8");
console.log(`phases: ${rows.length}`);
console.log(`complete: ${complete.length}`);
console.log(`missing L4: ${missingL4.length}`);
console.log(`missing L5: ${missingL5.length}`);
console.log(`plan written: ${OUT}`);
